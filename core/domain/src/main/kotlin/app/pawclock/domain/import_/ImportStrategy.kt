package app.pawclock.domain.import_

/**
 * Стратегия слияния импортируемых питомцев с уже существующими в репозитории (§3.5, Plan 2 Task 19).
 *
 *  - [MERGE] — существующие питомцы сохраняются, импортируемые добавляются рядом (без дедупликации:
 *    у импортируемых нет стабильного ключа — `id` не экспортируется, а совпадение имён не означает
 *    тождества питомца).
 *  - [REPLACE] — репозиторий полностью очищается перед вставкой импортируемых (восстановление из
 *    бэкапа «как было»).
 */
enum class ImportStrategy {
    MERGE,
    REPLACE,
}
