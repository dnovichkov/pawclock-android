package app.pawclock.domain.import_

/**
 * Нефатальное замечание, накопленное при импорте (§3.5 спецификации, Plan 2 Task 19).
 *
 * В отличие от [ImportException], предупреждение не прерывает импорт — запись принимается,
 * а проблемное необязательное поле деградирует к безопасному значению (обычно `null`).
 * UI (Task 21) показывает сводку предупреждений после успешного импорта.
 */
sealed interface ImportWarning {
    /**
     * `gender_id` записи не распознан как [app.pawclock.model.Gender] — пол отброшен к `null`
     * (lenient), запись импортирована. В отличие от вида, пол — косметическое необязательное
     * поле, и неизвестное значение не оправдывает отказ от всей записи.
     *
     * @property petName имя питомца, к которому относится предупреждение
     * @property genderId нераспознанный идентификатор пола из ввода
     */
    data class UnknownGender(
        val petName: String,
        val genderId: String,
    ) : ImportWarning
}
